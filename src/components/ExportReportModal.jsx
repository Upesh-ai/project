import React, { useState } from 'react';
import { 
  X, 
  Copy, 
  Check, 
  FileDown, 
  Printer, 
  FileText 
} from 'lucide-react';

export function ExportReportModal({ analysis, onClose }) {
  const [copied, setCopied] = useState(false);

  if (!analysis) return null;

  const generateMarkdownReport = () => {
    const { meta, trustDashboard, structuredFacts, informationGaps, contradictions, outdatedWarnings, verifyChecklist } = analysis;

    return `# DIGITAL DARK SPOT - ANALYSIS REPORT
**AI-Assisted Information Gap Detection Platform**
Shinchan Online Hackathon 2026 | Presented by Upesh Chauhan (Roll No.: 2404851520061)

---

## 1. Executive Summary
- **Topic:** ${meta.topic}
- **Research Goal:** ${meta.researchGoal}
- **Analyzed At:** ${meta.analyzedAt}
- **Sources Evaluated:** ${meta.sourceCount}
- **Reliability Index:** ${trustDashboard.reliabilityScore}% (${trustDashboard.statusText})

### Trust Composition Ratio (Slide 7)
- **Sourced Evidence:** ${trustDashboard.breakdown.sourced.percentage}%
- **AI-Suggested Inferences:** ${trustDashboard.breakdown.aiInferred.percentage}%
- **Uncertain / Dark Spots:** ${trustDashboard.breakdown.uncertain.percentage}%

---

## 2. Prioritized "Verify Next" Action Checklist (Slide 5)
${verifyChecklist.map((item, i) => `${i + 1}. [${item.completed ? 'X' : ' '}] **[${item.priority}] ${item.title}**
   - Action: ${item.action}
   - Target Contact: ${item.targetEntity}
   - Evidence Citation: "${item.sourceEvidence.excerpt}" (${item.sourceEvidence.sourceTitle})
`).join('\n')}

---

## 3. Detected Information Gaps (Unanswered Questions)
${informationGaps.map((gap, i) => `### Gap ${i + 1}: ${gap.title} [${gap.severity}]
- **Unanswered Question:** "${gap.question}"
- **Risk:** ${gap.whyItMatters}
- **Recommended Verification:** ${gap.recommendedAction}
`).join('\n')}

---

## 4. Contradictions & Clashing Statements
${contradictions.map((c, i) => `### Conflict ${i + 1}: ${c.title} [${c.severity}]
- **Source A (${c.sourceA.title}):** "${c.sourceA.claim}"
  * Quote: "${c.sourceA.quote}"
- **Source B (${c.sourceB.title}):** "${c.sourceB.claim}"
  * Quote: "${c.sourceB.quote}"
- **Real-World Impact:** ${c.impact}
`).join('\n')}

---

## 5. Outdated Guidelines & Expired Cycles
${outdatedWarnings.map((w, i) => `### Warning ${i + 1}: ${w.sourceTitle} [${w.severity}]
- **Cycle Detected:** ${w.outdatedSignal}
- **Date:** ${w.publishedDate}
- **Excerpt:** "${w.quote}"
- **Risk:** ${w.risk}
- **Correction:** ${w.suggestedFix}
`).join('\n')}

---
*Report generated by Digital Dark Spot - "Not just finding information, but knowing what to verify next."*
`;
  };

  const reportText = generateMarkdownReport();

  const handleCopy = () => {
    navigator.clipboard.writeText(reportText);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const blob = new Blob([reportText], { type: 'text/markdown;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.setAttribute('download', `digital-dark-spot-report-${Date.now()}.md`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/85 backdrop-blur-md animate-fade-in">
      <div className="bg-slate-900 border border-slate-700 rounded-2xl max-w-3xl w-full p-6 shadow-2xl shadow-black relative flex flex-col max-h-[90vh]">
        
        {/* Header */}
        <div className="flex items-center justify-between pb-3 border-b border-slate-800">
          <div className="flex items-center gap-2">
            <FileText className="w-5 h-5 text-blue-400" />
            <h3 className="font-bold text-white text-base">
              Export Analysis Audit Report
            </h3>
          </div>

          <button
            onClick={onClose}
            className="p-1 rounded-lg text-slate-400 hover:text-white hover:bg-slate-800 transition-colors"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Preview Area */}
        <div className="my-4 p-4 rounded-xl bg-slate-950 border border-slate-800 overflow-y-auto flex-1 font-mono text-xs text-slate-300 whitespace-pre-wrap selection:bg-blue-600">
          {reportText}
        </div>

        {/* Action Buttons */}
        <div className="flex flex-wrap items-center justify-between gap-3 pt-3 border-t border-slate-800">
          <div className="text-xs text-slate-400">
            Export ready in standard Markdown format
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handlePrint}
              className="inline-flex items-center gap-1.5 px-3.5 py-2 rounded-xl text-xs font-bold bg-slate-800 hover:bg-slate-700 text-slate-200 transition-colors"
            >
              <Printer className="w-3.5 h-3.5" />
              <span>Print / PDF</span>
            </button>

            <button
              onClick={handleCopy}
              className="inline-flex items-center gap-1.5 px-3.5 py-2 rounded-xl text-xs font-bold bg-slate-800 hover:bg-slate-700 text-slate-200 transition-colors"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copied ? 'Copied!' : 'Copy to Clipboard'}</span>
            </button>

            <button
              onClick={handleDownload}
              className="inline-flex items-center gap-1.5 px-4 py-2 rounded-xl text-xs font-bold bg-blue-600 hover:bg-blue-500 text-white transition-colors shadow-md"
            >
              <FileDown className="w-3.5 h-3.5" />
              <span>Download .MD File</span>
            </button>
          </div>
        </div>

      </div>
    </div>
  );
}
